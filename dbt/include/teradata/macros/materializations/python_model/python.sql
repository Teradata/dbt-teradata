{#
    Client-side Python model support (IDE-24196).

    teradata__py_write_table builds the full Python program that the
    TeradataClientPythonJobHelper executes in the dbt runner process. The
    incoming `compiled_code` already defines model(), ref(), source(), config,
    this and dbtObj (from dbt-core's py_script_postfix). We append the wiring
    that runs the model and writes the result. The names load_df_function,
    session and teradata__write_df are injected into the exec namespace by the
    helper (see dbt/adapters/teradata/python_submissions.py).
#}

